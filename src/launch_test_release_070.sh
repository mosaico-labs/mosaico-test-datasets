#!/usr/bin/env bash
#
# Launch a DETACHED tmux session that ingests + reconstructs rosbags for every
# dataset, one dataset at a time. Within a dataset, reconstruction runs ONLY if
# ingestion succeeds. Each command's logs go to its own file.
#
#   Attach to watch live : tmux attach -t test-release-070
#   Detach again         : press  Ctrl-b  then  d
#   List sessions        : tmux ls
#   Kill the session     : tmux kill-session -t test-release-070
#
set -euo pipefail

# ---------------------------------------------------------------------------
# Configuration  — everything you might want to change lives here
# ---------------------------------------------------------------------------
SESSION="test-release-070"
POETRY_DIR="/home/mosaico/workspace/mosaico-test-datasets"   # poetry project (contains pyproject.toml)
OUT_DIR="/home/mosaico/work/statistics/070826"               # where the .txt log files are written

# How each tool is invoked. The dotted names look like Python modules:
RUN="poetry run"

# Datasets to process, in order.
DATASETS=(nvidia agrikola autoware uzh_fpv sugarbeets unipi)

# false -> a failed dataset is logged and the run continues with the next one.
# true  -> the whole run stops the moment any dataset fails.
STOP_ON_ERROR=false
# ---------------------------------------------------------------------------

mkdir -p "$OUT_DIR"

# Refuse to clobber an existing session of the same name.
if tmux has-session -t "$SESSION" 2>/dev/null; then
  echo "A tmux session named '$SESSION' already exists."
  echo "  Attach : tmux attach -t $SESSION"
  echo "  Kill   : tmux kill-session -t $SESSION"
  exit 1
fi

# Generate the script that will actually run *inside* the tmux session.
RUNNER="$OUT_DIR/run_${SESSION}.sh"
cat > "$RUNNER" <<RUNNER_EOF
#!/usr/bin/env bash
# Auto-generated by launch_test_release_070.sh — runs inside tmux session '$SESSION'.

cd '$POETRY_DIR' || { echo "ERROR: cannot cd to $POETRY_DIR"; exec bash; }

RUN="$RUN"
OUT_DIR='$OUT_DIR'
STOP_ON_ERROR=$STOP_ON_ERROR
DATASETS=(${DATASETS[*]})

for ds in "\${DATASETS[@]}"; do
  echo "===== [\$(date '+%F %T')] START \$ds ====="
  ok=true

  # Ingest first. '>' + 2>&1 captures ALL output (stdout AND stderr) to the log.
  if ! \$RUN mosaicolabs.datasets.ingest_rosbags --datasets "\$ds" > "\$OUT_DIR/ingest_\${ds}.txt" 2>&1; then
    echo "!!!!! [\$(date '+%F %T')] INGEST FAILED \$ds — skipping reconstruction !!!!!"
    ok=false
  # Reconstruct runs ONLY because ingest above succeeded.
  elif ! \$RUN mosaicolabs.datasets.reconstruct_rosbags --datasets "\$ds" > "\$OUT_DIR/reconstruction_\${ds}.txt" 2>&1; then
    echo "!!!!! [\$(date '+%F %T')] RECONSTRUCT FAILED \$ds !!!!!"
    ok=false
  fi

  if \$ok; then
    echo "===== [\$(date '+%F %T')] DONE  \$ds ====="
  elif [ "\$STOP_ON_ERROR" = true ]; then
    echo ">>> STOP_ON_ERROR is set — aborting the remaining datasets."
    break
  fi
done

echo
echo "All datasets processed. Logs are in \$OUT_DIR"
echo "This shell stays open so you can inspect things — type 'exit' to close it."
RUNNER_EOF
chmod +x "$RUNNER"

# Start detached; run the job; then drop into an interactive shell so the
# session stays alive and browsable even after the job finishes.
tmux new-session -d -s "$SESSION" "bash '$RUNNER'; exec bash"

echo "Started detached tmux session '$SESSION'."
echo
echo "  Watch live   : tmux attach -t $SESSION        (detach with Ctrl-b then d)"
echo "  Tail a log   : tail -f $OUT_DIR/injest_agrikola.txt"
echo "  List sessions: tmux ls"
echo "  Kill it      : tmux kill-session -t $SESSION"
